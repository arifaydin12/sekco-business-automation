'use strict';

/**
 * Builds the static demo into docs/ (served by GitHub Pages from branch main, folder /docs).
 * The front end from public/ is copied as-is; only config.js is replaced so the app runs against the
 * in-browser mock API (localStorage) instead of the HTTP API. All asset paths are relative, so the site
 * works from any sub-path such as /sekco-business-automation/.
 *
 *   npm run build:demo
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'public');
const OUT = path.join(ROOT, 'docs');

function copyDir(from, to) {
    fs.mkdirSync(to, { recursive: true });
    for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
        const source = path.join(from, entry.name);
        const target = path.join(to, entry.name);
        if (entry.isDirectory()) copyDir(source, target);
        else fs.copyFileSync(source, target);
    }
}

fs.rmSync(OUT, { recursive: true, force: true });
copyDir(SRC, OUT);

// Demo data shared with scripts/seed.js
fs.mkdirSync(path.join(OUT, 'data'), { recursive: true });
fs.copyFileSync(path.join(ROOT, 'data', 'seed.json'), path.join(OUT, 'data', 'seed.json'));

// Enable demo mode
fs.writeFileSync(
    path.join(OUT, 'config.js'),
    '// Generated by "npm run build:demo". Do not edit - edit public/ and rebuild.\nwindow.SEKCO_CONFIG = { demo: true };\n'
);

// GitHub Pages: do not run Jekyll over the files
fs.writeFileSync(path.join(OUT, '.nojekyll'), '');

const files = [];
(function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(full);
        else files.push(path.relative(OUT, full));
    }
})(OUT);
console.log(`Demo built in docs/ (${files.length} files).`);
